const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript')
const exportsMap={}
const code=ts.transpileModule(fs.readFileSync('src/lesson-progress.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText
new Function('exports',code)(exportsMap)
const {lessonProgressMap}=exportsMap
const key='lesson',checkin=(rating,extra={})=>({key,rating,attended:true,...extra})
const session=(id,rating,duration=30,extra={})=>({id,rating,duration,lessonKeys:[key],updatedAt:id,...extra})
const value=(learningCheckins=[],learningSessions=[],scoreEvents=[])=>lessonProgressMap({learningCheckins,learningSessions,scoreEvents}).get(key)||{green:0,yellow:0}
assert.deepEqual(value(),{green:0,yellow:0})
assert.equal(value([checkin('struggling')]).yellow,1)
assert.equal(value([checkin('partial')]).yellow,2)
assert.equal(value([checkin('understood')]).yellow,3)
assert.equal(value([checkin('understood',{understandingSelected:false})]).yellow,1)
assert.equal(value([checkin('understood',{attended:false})]).yellow,0)
assert.equal(value([], [session('1','struggling')]).green,1)
assert.equal(value([], [session('1','partial')]).green,2)
assert.equal(value([], [session('1','understood')]).green,3)
assert.equal(value([], [session('1','understood'),session('2','understood')]).green,4)
assert.equal(value([], [session('1','understood',20),session('2','understood',20)]).green,4)
assert.equal(value([], [session('1','understood',30),session('2','understood',30,{lessonKeys:[key,'other']})]).green,4,'Time is not a mastery requirement')
assert.equal(value([], [session('1','understood'),session('2','struggling')]).green,1,'Latest learning rating is used')
assert.equal(value([], [session('1','understood')],[{sourceId:'1',type:'study-minutes',reversedAt:'now'}]).green,0)
assert.equal(value([], [],[{sourceId:key,type:'content-learned'}]).green,1,'Legacy learned bonuses remain visible')
assert.equal(value([], [session('1','understood',1),session('2','understood',1)]).green,4,'No minimum duration')
assert.equal(value([], [session('1','understood'),session('2','understood'),session('3','partial')]).green,2,'Latest feedback can regress')
assert.equal(value([], [session('1','understood'),session('2','partial'),session('3','understood')]).green,3,'Partial feedback resets the good run')
assert.equal(value([], [session('1','understood'),session('2','partial'),session('3','understood'),session('4','understood')]).green,4)
assert.equal(value([], [session('2','partial'),session('1','understood')]).green,2,'Chronological order, not array order')
assert.equal(value([], [session('1','understood'),session('1','understood')]).green,3,'Duplicate sessions do not count twice')
const mixed=value([checkin('understood')],[session('1','partial')])
assert.equal(mixed.green,2);assert.equal(mixed.yellow,3,'Individual bars can mix green and yellow')
const dashboard=fs.readFileSync('src/OverviewDashboard.tsx','utf8')
assert.ok(dashboard.indexOf('Nächste Veranstaltung')<dashboard.indexOf("label:'Nächste Hausaufgabe'"))
const management=fs.readFileSync('src/StudyManagement.tsx','utf8')
assert.ok(!management.includes('Abschlussdatum'))
assert.ok(!management.includes('Aktuelle Module gehören fest'))
console.log('PASS: four-bar status, visits, learning ratings, repetition threshold, shared minutes, reversals, legacy progress, dashboard order and simplified semester form')
